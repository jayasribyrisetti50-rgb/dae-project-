import pandas as pd

file_path = "/content/vizag_weather_2_years.csv..xlsx"

df = pd.read_excel(file_path, sheet_name="Daily Data")

df["Date"] = pd.to_datetime(df["Date"])

df["Year"] = df["Date"].dt.year
df["Month"] = df["Date"].dt.month

# Monthly aggregation
monthly_data = df.groupby(["Year", "Month"]).agg({
    "Temp_C": "mean",
    "Rainfall_mm": "mean"
}).reset_index()

print("Monthly Aggregated Data:")
print(monthly_data)

# Seasonal aggregation
seasonal_data = df.groupby("Season").agg({
    "Temp_C": "mean",
    "Rainfall_mm": "mean"
}).reset_index()

print("\nSeasonal Aggregated Data:")
print(seasonal_data)

